/// </summary>
public enum Shade
{
	/// <summary>
	/// A button with lighter styling.
	/// </summary>
	Lighter,
	/// <summary>
	/// A button with light styling.
	/// </summary>
	Light,
	/// <summary>
	/// A button with default styling.
	/// </summary>
	Default,
	/// <summary>
	/// A button with dark styling.
	/// </summary>
	Dark,
	/// <summary>
	/// A button with darker styling.
	/// </summary>
	Darker
}
